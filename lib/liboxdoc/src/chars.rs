/// The UTF-8 and ASCII forms of special character `name`, if it is one.
pub fn lookup(name: &str) -> Option<(&'static str, &'static str)> {
    CHARS.binary_search_by(|(n, _, _)| n.cmp(&name)).ok().map(|i| (CHARS[i].1, CHARS[i].2))
}
