/// The ASCII form of `c`, if mandoc has one.
pub fn lookup(c: char) -> Option<&'static str> {
    UNICODE_ASCII.binary_search_by_key(&(c as u32), |(k, _)| *k).ok().map(|i| UNICODE_ASCII[i].1)
}
