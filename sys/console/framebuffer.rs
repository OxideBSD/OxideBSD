//! Rasterizes `console::vga`'s own real ANSI/VT100 text buffer onto Limine's linear framebuffer --
//! the real replacement for that module's now-unusable direct VGA-hardware text mirror (see
//! `boot::primary_framebuffer`'s own doc comment for why: the legacy `0xb8000` text buffer simply
//! isn't backed by anything under Limine, on either BIOS or UEFI, confirmed live). A real
//! Limine-provided framebuffer, by contrast, genuinely exists either way and comes back as an
//! already-mapped, directly dereferenceable pointer -- no HHDM offset math, no legacy-hardware
//! assumption.
//!
//! **Deliberately a dumb rasterizer, not its own text engine**: `console::vga::Writer` already has
//! a real, working ANSI/VT100 CSI parser (colors, cursor moves, scroll regions, alt-screen for
//! `vi`) -- it just writes into an ordinary in-memory buffer now instead of real VRAM (see that
//! module's own `SHADOW_BUFFER` doc comment). This module's only job is `redraw()`: read that
//! buffer's current content cell-by-cell (`vga::for_each_cell`) and paint real pixels, so the
//! *entire* existing ANSI engine keeps working completely unmodified, colors included, instead of
//! reimplementing a second, worse one from scratch.
//!
//! Font: the **real, authentic** IBM/CGA/VGA ROM CP437 bitmap font -- not a modern lookalike.
//! `VGAFONT16` below is copied verbatim from SeaBIOS's own `vgasrc/vgafonts.c` (the actual BIOS
//! text-mode font QEMU itself displays), whose own header comment states plainly: "These fonts
//! come from ftp://ftp.simtel.net/pub/simtelnet/msdos/screen/fntcol16.zip[,] ... (c) by Joseph
//! Gil[,] [t]he individual fonts are public domain" -- SeaBIOS's own surrounding code is GPLv3,
//! but this specific data predates and is unrelated to that license by its own explicit
//! statement, exactly why "vgafont8"/"vgafont16" arrays are already copied verbatim into dozens
//! of differently, permissively-licensed bootloader/OS projects across GitHub. 256 glyphs
//! (full CP437, not just ASCII), genuinely 8x16 (not an 8x8 font stretched), **MSB-first bit
//! order** (bit 7 is each row's leftmost pixel -- confirmed against the real, recognizable CP437
//! 0x01 "smiley face" glyph's own byte pattern, the opposite convention from a `font8x8_basic`-
//! style LSB-first font), nearest-neighbor-scaled per cell to fill the *entire* real display (see
//! `RedrawTarget`'s own doc comment) -- real VGA text mode always filled the whole physical
//! screen, not a fixed 640x400 window centered inside a larger one (tried that first; found live
//! that it left real, visible letterboxing on any display bigger than exactly 640x400).
//!
//! Colors: the real, standard 16-color CGA/VGA palette (`PALETTE` below) -- not a flat two-tone
//! grey-on-black -- driven directly by `vga::Cell`'s own real `fg`/`bg` palette indices, which
//! `vga::Writer`'s existing SGR handling already computes correctly for every color BusyBox's
//! `hush`/`vi`/coloured `ls` etc. actually use.

use core::sync::atomic::{AtomicBool, Ordering};

use crate::boot::FbInfo;

/// Set while a userland process holds a real `/dev/fb0` physical mmap (`process::mm::do_mmap_fb`)
/// -- `redraw()` below early-returns while this is set. Load-bearing, not a nicety: this module's
/// own rasterizer writes real pixels with no locking and no awareness of userland writes (see
/// this file's own module doc comment), diffing against `PREV_CELLS`' *shadow text buffer*
/// content, never actual VRAM -- so left unguarded, the very next `serial_println!` anywhere in
/// the kernel would silently overwrite arbitrary rectangles of a mapped process's own pixels with
/// stale glyph content. Cleared once no such mapping remains (see `process::mm`'s
/// `cleanup_mmap_phys_regions_for_exit`/`do_munmap`).
///
/// **Known simplification**: a single global flag, not reference-counted across every process
/// that might independently hold a mapping -- matches this kernel's existing "exactly one real
/// console, no multi-session concept" precedent (`console::stdin`'s own `CONTROLLING_SESSION`/
/// `FOREGROUND_PGID` are the same shape). Two *separate* processes (not `CLONE_THREAD` siblings,
/// who already share one `ThreadGroupShared`/one region list) both mapping `/dev/fb0` at once,
/// where one unmaps first, would incorrectly resume `redraw()` while the other still owns the
/// screen -- not a scenario any real consumer of this primitive creates today (one process, one
/// display), so left as a documented gap rather than a real per-mapping refcount.
static FB_OWNED_BY_USERSPACE: AtomicBool = AtomicBool::new(false);

pub fn set_owned_by_userspace(owned: bool) {
    FB_OWNED_BY_USERSPACE.store(owned, Ordering::Relaxed);
}

