/// Packs an 8-bit-per-channel color into this framebuffer's own real pixel format (mask
/// size/shift, not assumed to be a fixed XRGB8888 layout even though that's what OVMF/QEMU's
/// stdvga always reports in practice) -- truncates precision if a channel's real mask is narrower
/// than 8 bits (e.g. a 565 format), exact whenever it's a full 8.
fn pack_rgb(fb: &FbInfo, r: u8, g: u8, b: u8) -> u32 {
    let chan = |value: u8, size: u8, shift: u8| -> u32 {
        if size == 0 {
            return 0;
        }
        ((value as u32) >> (8 - size.min(8))) << shift
    };
    chan(r, fb.red_mask_size, fb.red_mask_shift)
        | chan(g, fb.green_mask_size, fb.green_mask_shift)
        | chan(b, fb.blue_mask_size, fb.blue_mask_shift)
}

/// Native glyph/cell extent -- `VGAFONT16`'s own real, unscaled shape, used as-is (no scaling at
/// all). Real VGA text mode always filled the entire physical display by fitting *more real
/// columns and rows* of a fixed-size character cell into it, not by stretching a fixed 80x25 grid
/// to fill whatever resolution happens to be in use -- tried the latter first (both a fixed
/// 640x400 window centered inside a larger real resolution, and non-integer nearest-neighbor
/// stretching to fill it); both looked visibly wrong (black-bar letterboxing, and uneven/
/// distorted glyphs, respectively) once actually looked at. `console::vga::real_grid_size` is
/// what actually makes this fill the screen: it sizes the *grid itself* (`vga::width()`/
/// `height()`) to however many native `GLYPH_WIDTH`x`GLYPH_HEIGHT` cells fit the real
/// framebuffer, so a bigger real display shows more real characters, not bigger ones.
const GLYPH_WIDTH: usize = 8;
const GLYPH_HEIGHT: usize = 16;

/// Re-derived on every `redraw()` call, not cached: nothing here is expensive enough to be worth
/// the staleness risk of caching Limine's own response across calls.
struct RedrawTarget {
    base: *mut u8,
    pitch: usize,
    fb_width: usize,
    fb_height: usize,
    x_offset: usize,
    y_offset: usize,
}

impl RedrawTarget {
    fn put_pixel(&self, x: usize, y: usize, color: u32) {
        if x >= self.fb_width || y >= self.fb_height {
            return;
        }
        let offset = y * self.pitch + x * 4;
        // SAFETY: offset < fb_height * pitch (checked above), and this console only ever
        // constructs a `RedrawTarget` (see `redraw_target` below) for a real
        // 32-bit-per-pixel framebuffer.
        unsafe {
            core::ptr::write_volatile(self.base.add(offset) as *mut u32, color);
        }
    }

    /// Draws one real, native `GLYPH_WIDTH`x`GLYPH_HEIGHT` cell (`VGAFONT16` covers the full
    /// 256-entry CP437 range, so every `u8` value has a real glyph -- no fallback/substitution
    /// needed) at pixel origin `(x0, y0)`, a direct 1:1 blit (no scaling -- see `GLYPH_WIDTH`'s
    /// own doc comment for why).
    fn draw_cell(&self, x0: usize, y0: usize, ascii: u8, fg: u32, bg: u32) {
        let glyph = &VGAFONT16[ascii as usize];
        for (gy, bits) in glyph.iter().enumerate() {
            for gx in 0..GLYPH_WIDTH {
                // MSB-first: bit 7 is the leftmost pixel -- see this module's own doc comment.
                let color = if bits & (0x80 >> gx) != 0 { fg } else { bg };
                self.put_pixel(x0 + gx, y0 + gy, color);
            }
        }
    }
}

/// Previous redraw's real content, per cell (`ascii`, `fg`, `bg`) -- lets `redraw()` below only
/// touch pixels for cells that actually changed instead of repainting the entire grid every
/// single call. **Load-bearing, not an optimization nicety**: found live, the hard way --
/// rasterizing the *entire* grid on every single `serial_println!` visibly stalled real boot
/// progress for minutes under software TCG rendering, since boot alone issues dozens of prints.
/// `None` means "never drawn," forcing that cell's first real paint. Sized to
/// `vga::MAX_WIDTH`x`MAX_HEIGHT` (this boot's real, active grid -- `vga::width()`/`height()` --
/// is a runtime value now, not a `const`, so this can't be sized to it directly; only the real
/// active sub-region is ever actually touched, see `redraw()` below). `static mut`, not `static`,
/// for the same reason `console::vga::SHADOW_BUFFER` is (see that static's own doc comment).
static mut PREV_CELLS: [[Option<(u8, u8, u8)>; crate::console::vga::MAX_WIDTH];
    crate::console::vga::MAX_HEIGHT] =
    [[None; crate::console::vga::MAX_WIDTH]; crate::console::vga::MAX_HEIGHT];

/// The cursor's own position as of the *previous* redraw -- needed so a cursor that merely moved
/// (no character/color change at either its old or new cell) still gets its old mark erased and
/// new one drawn, even though `PREV_CELLS` alone would see "nothing changed" at either cell.
static mut PREV_CURSOR: Option<(usize, usize)> = None;

fn redraw_target() -> Option<RedrawTarget> {
    let fb = crate::boot::primary_framebuffer()?;
    // Only 32-bit-per-pixel formats are supported (universal in practice for OVMF/QEMU's
    // stdvga) -- checked rather than assumed, matching this codebase's own "validate and
    // decline loudly, never silently corrupt" convention elsewhere (e.g.
    // `module::apply_relocation`'s own overflow checks).
    if fb.bpp != 32 {
        return None;
    }
    let fb_width = fb.width as usize;
    let fb_height = fb.height as usize;
    // Native, unscaled cell size (see `GLYPH_WIDTH`/`GLYPH_HEIGHT`'s own doc comment):
    // `console::vga::real_grid_size` already sized *the grid itself* (more real columns/rows, not
    // bigger characters) to fill the real display at this exact native cell size, so by
    // construction `grid_width`/`height` below come out at most one `GLYPH_WIDTH`/`HEIGHT` short
    // of `fb_width`/`height` (real leftover only ever a few pixels, from integer division --
    // centering it is purely cosmetic, not a return to real letterboxing).
    let grid_width = crate::console::vga::width() * GLYPH_WIDTH;
    let grid_height = crate::console::vga::height() * GLYPH_HEIGHT;
    Some(RedrawTarget {
        base: fb.address as *mut u8,
        pitch: fb.pitch as usize,
        fb_width,
        fb_height,
        x_offset: fb_width.saturating_sub(grid_width) / 2,
        y_offset: fb_height.saturating_sub(grid_height) / 2,
    })
}

/// Repaints only the cells that actually changed since the previous call (see `PREV_CELLS`'s own
/// doc comment for why this is load-bearing, not just an optimization), then redraws the cursor
/// mark. Called after every `serial_println!`/`serial_print!` (see `console::serial::_print`,
/// this function's only real caller). No-op if Limine reported no usable framebuffer at all, or
/// if a userland process currently holds a real `/dev/fb0` mmap (see `FB_OWNED_BY_USERSPACE`'s
/// own doc comment).
#[allow(clippy::deref_addrof)] // false positive: `&raw mut` + deref avoids a deny-by-default
// direct `&mut` to (part of) a mutable static (edition 2024 `static_mut_refs`)
pub fn redraw() {
    if FB_OWNED_BY_USERSPACE.load(Ordering::Relaxed) {
        return;
    }
    let Some(target) = redraw_target() else {
        return;
    };
    let fb = match crate::boot::primary_framebuffer() {
        Some(fb) => fb,
        None => return,
    };

    let (cursor_row, cursor_col, cursor_visible) = crate::console::vga::cursor();
    // SAFETY: single-threaded, `without_interrupts`-wrapped by every real caller
    // (`console::serial::_print`) -- no concurrent access to either static is possible.
    let prev_cursor = unsafe { (&raw const PREV_CURSOR).read() };

    crate::console::vga::for_each_cell(|row, col, cell| {
        let key = (cell.ascii, cell.fg, cell.bg);
        // SAFETY: see above. `&raw mut` + deref, not a direct `&mut PREV_CELLS[...]`, is required
        // -- taking a `&mut` to (any part of) a mutable static directly is `deny`-by-default under
        // edition 2024 (`static_mut_refs`).
        let slot = unsafe { &mut *(&raw mut PREV_CELLS[row][col]) };
        // A cell at the cursor's old or new position needs a real repaint even when its own
        // content is unchanged -- the cursor mark overlays real pixels `PREV_CELLS` alone has no
        // way to know were touched.
        let at_cursor_edge =
            (row, col) == (cursor_row, cursor_col) || Some((row, col)) == prev_cursor;
        if *slot != Some(key) || at_cursor_edge {
            let fg_rgb = PALETTE[cell.fg as usize];
            let bg_rgb = PALETTE[cell.bg as usize];
            let fg = pack_rgb(&fb, fg_rgb.0, fg_rgb.1, fg_rgb.2);
            let bg = pack_rgb(&fb, bg_rgb.0, bg_rgb.1, bg_rgb.2);
            target.draw_cell(
                target.x_offset + col * GLYPH_WIDTH,
                target.y_offset + row * GLYPH_HEIGHT,
                cell.ascii,
                fg,
                bg,
            );
            if cursor_visible && (row, col) == (cursor_row, cursor_col) {
                // A real two-scanline underline (the classic BIOS text-mode default shape -- see
                // `vga::CURSOR_SHAPE_START`/`_END`'s own comment for the real hardware equivalent
                // this mirrors), drawn in white so it stays legible against any background.
                let white = pack_rgb(&fb, 0xFF, 0xFF, 0xFF);
                let x0 = target.x_offset + col * GLYPH_WIDTH;
                let y0 = target.y_offset + (row + 1) * GLYPH_HEIGHT - 2;
                for gy in 0..2 {
                    for gx in 0..GLYPH_WIDTH {
                        target.put_pixel(x0 + gx, y0 + gy, white);
                    }
                }
            }
        }
        *slot = Some(key);
    });

    // SAFETY: see above.
    unsafe { (&raw mut PREV_CURSOR).write(Some((cursor_row, cursor_col))) };
}
