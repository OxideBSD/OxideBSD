#!/usr/bin/env python3
# mkcodepages.py DIR: writes the code page files mount_msdosfs(8)'s -D reads (installed in
# /usr/share/msdosfs) from unicode.org's Microsoft mapping files in DIR, as fetched from
# https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/{PC,WINDOWS}/CPnnn.TXT (the WINDOWS
# ones saved as WnnnTXT's names prefixed with W). Run by hand; the output is committed.
#
# Output, one file per code page, named as -D takes it (CP437, ...): comment lines, then one
# mapping per line, the code page's code and the Unicode character in hex. A code with "lead"
# instead is a double-byte code page's lead byte. Single-byte codes mapped to themselves (ASCII
# in every code page here) are left out; a code that isn't listed and isn't a lead is undefined.
import os
import sys

PC = [437, 737, 775, 850, 852, 855, 857, 860, 861, 862, 863, 864, 865, 866, 869, 874]
WINDOWS = [932, 936, 949, 950, 1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 1258]

def parse(path):
    version = "?"
    maps, leads = [], []
    for line in open(path, encoding="latin-1"):
        if "Table version:" in line:
            version = line.split(":", 1)[1].strip()
        if not line.startswith("0x"):
            continue
        cols = line.split("\t")
        code = int(cols[0], 16)
        uni = cols[1].strip()
        if "DBCS LEAD BYTE" in line:
            leads.append(code)
        elif uni.startswith("0x"):
            u = int(uni, 16)
            if code > 0xFF or code != u:
                maps.append((code, u))
    return version, maps, leads

def write(out_dir, name, source, version, maps, leads):
    with open(os.path.join(out_dir, name), "w") as f:
        f.write(f"# {name} for mount_msdosfs(8) -D, generated by mkcodepages.py from unicode.org's\n")
        f.write(f"# MAPPINGS/VENDORS/MICSFT/{source} (Microsoft, table version {version}).\n")
        f.write("# code unicode, hex; \"lead\": a double-byte lead byte.\n")
        for l in leads:
            f.write(f"{l:02x} lead\n")
        for c, u in maps:
            f.write(f"{c:02x} {u:04x}\n")

def main():
    src = sys.argv[1]
    out = os.path.dirname(os.path.abspath(__file__))
    for cp in PC:
        v, m, l = parse(os.path.join(src, f"CP{cp}.TXT"))
        write(out, f"CP{cp}", f"PC/CP{cp}.TXT", v, m, l)
        if cp == 850:
            # CP858 is CP850 with the euro sign in place of the dotless i (0xD5).
            m858 = [(c, 0x20AC if c == 0xD5 else u) for c, u in m]
            write(out, "CP858", "PC/CP850.TXT, euro at 0xD5", v, m858, l)
    for cp in WINDOWS:
        v, m, l = parse(os.path.join(src, f"W{cp}.TXT"))
        write(out, f"CP{cp}", f"WINDOWS/CP{cp}.TXT", v, m, l)

main()
